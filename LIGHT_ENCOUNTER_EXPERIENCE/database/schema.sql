-- Run in the Supabase SQL Editor.
create table if not exists public.registrations (
  id bigint generated by default as identity primary key,
  first_name text not null,
  surname text not null,
  phone text not null,
  email text not null,
  gender text not null check (gender in ('Male','Female')),
  church text not null,
  location text not null,
  school text not null,
  department text not null,
  heard_from text not null,
  expectations text not null,
  prayer_request text,
  serve_team text,
  available text not null check (available in ('Yes','No')),
  created_at timestamptz not null default now()
);
alter table public.registrations add column if not exists school text;
alter table public.registrations enable row level security;
-- Public visitors may submit a registration, but cannot read or delete records.
create policy "Anyone can submit registration" on public.registrations
for insert to anon, authenticated with check (true);
-- Only signed-in admins may read and delete. Create exactly three admin users
-- in Supabase Authentication > Users, then use this policy.
create policy "Admins can view registrations" on public.registrations
for select to authenticated using (auth.uid() in (select user_id from public.lee_admins));
create policy "Admins can delete registrations" on public.registrations
for delete to authenticated using (auth.uid() in (select user_id from public.lee_admins));
create table if not exists public.lee_admins (user_id uuid primary key references auth.users(id) on delete cascade);
